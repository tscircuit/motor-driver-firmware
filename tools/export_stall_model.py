"""Export the fitted six-feature model and its observed envelopes to C.
Usage: python tools/export_stall_model.py MODEL_JSON DATA_DIRECTORY
"""
import json,pathlib,sys,numpy as np
source=pathlib.Path(sys.argv[1]);folder=pathlib.Path(sys.argv[2]);model=json.loads(source.read_text());root=pathlib.Path(__file__).resolve().parents[1]
def features(q,speed):
 r=np.hypot(q[:,1],q[:,2]);p=q[:,3];mu=r.mean();pm=p.mean()
 return np.array([mu,r.std()/(mu+1e-8),pm/(mu+1e-8),p.std()/(pm+1e-8),np.sqrt(np.maximum(q[:,4],0).mean())/(mu+1e-8),np.abs(np.diff(r)).mean()/(mu*speed/1000+1e-8)])
def fmt(x):return f'{float(x):.10e}f'
def array(x):return '{'+','.join(fmt(v) for v in x)+'}'
profiles=[]
for speed_key,record in model['profiles'].items():
 speed=float(speed_key);fit=record['model'];n=record['selected']['window_ms'];coeff=np.zeros(6);coeff[fit['indices']]=np.array(fit['direction'])/fit['scale'];bias=-np.dot(fit['mid'],coeff[fit['indices']])-fit['boundary'];rows=[]
 for p in sorted(folder.glob('trial-*.json')):
  d=json.loads(p.read_text())
  if d['config']['speed']!=speed:continue
  q=np.array(d['bins']);q[:,0]=q[:,0]/1e6+d['clock_alignment']['offset_s']-d['start_host_time'];q=q[q[:,0]<9.8]
  rows.extend(features(q[i:i+n],speed) for i in range(0,len(q)-n+1,50))
 x=np.array(rows);spread=np.maximum(x.max(axis=0)-x.min(axis=0),[.05,.02,.01,.1,.01,.1]);low=np.maximum(0,x.min(axis=0)-spread*.5);high=x.max(axis=0)+spread*.5
 reliable=max(t['error'] for t in record['outer'])<=.1000001
 profiles.append((speed,n,coeff,bias,fit['span'],low,high,reliable))
text='''/* Generated by tools/export_stall_model.py. Do not edit coefficients by hand.
 * 24 user-labelled trials, requested 9 V, fixed 1/16 hardware microsteps.
 * Retrospective nested whole-trial validation; not independent motor validation.
 */
#ifndef STALL_MODEL_H
#define STALL_MODEL_H
#define STALL_MODEL_ID "nema17-20261016-v2"
#define STALL_MODEL_PROFILE_COUNT 4
#define STALL_MODEL_MIN_TEMP 32.1875f
#define STALL_MODEL_MAX_TEMP 42.1875f
typedef struct { float speed; unsigned window_ms; float coefficient[6], bias, span, low[6], high[6]; bool supported; } stall_model_profile_t;
static const stall_model_profile_t stall_profiles[STALL_MODEL_PROFILE_COUNT]={
'''
for speed,n,coef,bias,span,low,high,supported in profiles:text+=' {'+f'{fmt(speed)},{n},'+array(coef)+','+fmt(bias)+','+fmt(span)+','+array(low)+','+array(high)+','+('true' if supported else 'false')+'},\n'
text+='};\n#endif\n';(root/'firmware-c/stall_model.h').write_text(text)
(root/'firmware-c/calibration').mkdir(exist_ok=True);(root/'firmware-c/calibration/nema17-stall-20261016.json').write_text(source.read_text())
print('Exported',[(p[0],p[1],p[-1]) for p in profiles])
